import base64
from html.parser import HTMLParser

import pytest
from fastapi.testclient import TestClient

from app.mfa import totp_qr_image


SVG = '<svg xmlns="http://www.w3.org/2000/svg" width="220" height="220"><rect width="220" height="220"/></svg>'
# Supabase Auth uses SVGo, which emits an XML declaration and a comment.
PROVIDER_QR = '<?xml version="1.0"?>\n<!-- Generated by SVGo -->\n' + SVG
# goqrsvg writes every black AND white module as an individual rectangle.
# Use a realistic provider-sized grid, not just a one-rectangle placeholder.
PROVIDER_GRID = '<?xml version="1.0"?>\n<!-- Generated by SVGo -->\n<svg xmlns="http://www.w3.org/2000/svg" width="219" height="219">' + "".join(
    f'<rect x="{12+x*3}" y="{12+y*3}" width="3" height="3" style="fill:{"black" if (x+y)%2 else "white"};stroke:none"/>'
    for x in range(65) for y in range(65)
) + "</svg>"


class Images(HTMLParser):
    def __init__(self):
        super().__init__()
        self.sources = []

    def handle_starttag(self, tag, attrs):
        if tag == "img":
            values = dict(attrs)
            if values.get("alt") == "認証アプリに登録するQRコード":
                self.sources.append(values["src"])


@pytest.mark.parametrize("svg", [SVG, PROVIDER_QR, PROVIDER_GRID], ids=["svg", "xml-prolog", "provider-sized-grid"])
def test_provider_svg_with_xml_prolog_stays_in_image_context(svg):
    image = totp_qr_image(svg)
    assert image.startswith("data:image/svg+xml;base64,")
    assert base64.b64decode(image.split(",", 1)[1]).decode() == svg


@pytest.mark.parametrize("svg", [None, {}, "", "https://example.com/qr.svg", "<html/>", "<svg", '<!DOCTYPE svg [<!ENTITY x "test">]><svg>&x;</svg>', "<svg>" + " " * (4 * 1024 * 1024) + "</svg>"], ids=["null", "object", "empty", "remote-url", "html", "malformed", "entity", "oversized"])
def test_non_svg_or_unsafe_provider_output_is_not_used_as_image_source(svg):
    assert totp_qr_image(svg) == ""


@pytest.mark.parametrize("svg", [PROVIDER_QR, PROVIDER_GRID, ""], ids=["xml-prolog", "provider-sized-grid", "missing"])
def test_enrollment_renders_qr_or_explicit_manual_fallback(monkeypatch, svg):
    from app.main import app, mfa

    async def enroll(request):
        return {"id": "05c96b3b-aa7e-4f9e-b3d8-b5bce5acfe2b", "totp": {"qr_code": svg, "secret": "LOCAL-TEST-ONLY"}}

    monkeypatch.setattr(mfa, "enroll", enroll)
    client = TestClient(app)
    client.get("/auth/demo", follow_redirects=False)
    response = client.post("/security/mfa/enroll", data={"next": "/admin"})
    assert response.status_code == 200
    images = Images()
    images.feed(response.text)
    if svg:
        assert len(images.sources) == 1
        assert base64.b64decode(images.sources[0].split(",", 1)[1]).decode() == svg
        assert "QRコードを表示できませんでした" not in response.text
        assert "<?xml" not in response.text
    else:
        assert images.sources == []
        assert "QRコードを表示できませんでした" in response.text
        assert "<details open>" in response.text
    assert "スマートフォンに認証アプリを用意" in response.text
    assert "App StoreまたはGoogle Play" in response.text
    assert "スマートフォン1台で設定する" in response.text
    assert 'value="/admin"' in response.text
